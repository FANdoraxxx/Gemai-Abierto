def _greedy_non_adjacent(comp, k, min_bad):
    order = sorted(range(len(comp)), key=lambda j: -comp[j]["total"])
    out = []
    for j in order:
        if comp[j]["total"] <= min_bad:
            break
        if all(abs(j - x) >= 2 for x in out):
            out.append(j)
        if len(out) >= k:
            break
    return sorted(out)


def _pass_schedule(p):
    """Odd -> even -> worst-non-adjacent, then cycle odd -> even with fresh RNG rounds."""
    cycle = int(p) % 5
    return ("odd", "even", "worst-nonadj", "odd", "even")[cycle]


def infill_refine(q, records, log=print):
    o = q.options
    out = []
    n = len(records)
    if getattr(q.infill.V, "FUT", None) is None:
        log("warning: infill model has no FUT token (not an infill checkpoint); infill refinement skipped", flush=True)
        return [dict(pass_=1, skipped="no-fut-vocab")]
    k = max(1, int(math.ceil(o.infill_frac * n)))
    for p in range(int(o.infill_passes)):
        t0 = time.perf_counter()
        comp, ev = infill_window_badness(q, records)
        q.last_events = ev
        schedule = _pass_schedule(p)
        if schedule == "odd":
            cand = [j for j in range(1, n) if j % 2 == 1]
            cand.sort(key=lambda j: -comp[j]["total"])
            targets = sorted(cand[:k])
        elif schedule == "even":
            cand = [j for j in range(0, n) if j % 2 == 0]
            cand.sort(key=lambda j: -comp[j]["total"])
            targets = sorted(cand[:k])
        else:
            targets = _greedy_non_adjacent(comp, k, o.infill_min_bad)
        details, changed = [], 0
        for i in targets:
            if i >= n - 1:
                continue
            ok, info = yield from infill_refine_window(q, records, i, p, log)
            info["before"] = round(comp[i]["total"], 3)
            details.append(info)
            changed += int(ok)
            if ok:
                q.last_events = None
            log(f"infill pass {p + 1} window {i + 1}/{n}: bad={comp[i]['total']:.2f} " +
                ("replaced (-%.2f)" % info["delta"] if ok else f"kept ({info.get('reason', '')})"), flush=True)
        out.append(dict(pass_=p + 1, schedule=schedule,
                        targets=targets, changed=changed, seconds=round(time.perf_counter() - t0, 2),
                        total_before=round(sum(c["total"] for c in comp), 3),
                        windows=details, hard_before=int(sum(c.get("hard", 0) for c in comp))))
        # Keep going: an empty odd pass must not prevent the even / worst passes from
        # exploring the remaining windows (important for the stricter R2/R3 Pareto gate).
    return out
