"""V6 infill refinement at generation time (FUT token).

The whole chart is generated by the normal V6 Chorus D2 pipeline (pass 1).  Then ``infill_refine``
regenerates selected 4-bar windows with the infill model conditioned on
  (a) the preceding 16 beats of the already generated chart (CTX), and
  (b) the following 8 beats (2 bars) of the draft chart (FUT),
exactly the layout the model was trained on.  Candidates are scored by the mandatory 5-part cost:
surprise / qmode / distribution anomaly / seam / chorus-vs-verse role, with the replacement margin.

Pass schedule (--infill-passes 3 --infill-frac 0.25):
  pass 1: highest-cost ODD window indices,  pass 2: highest-cost EVEN indices (costs recomputed),
  pass 3: greedily highest-cost NON-ADJACENT windows over the whole chart.  Further passes
  cycle odd -> even with fresh RNG rounds; --infill-seed-offset / --infill-round give each
  evolution round an independent candidate bank.
"""
from __future__ import annotations

import math
import time
from collections import Counter
from types import SimpleNamespace

import numpy as np
import torch
import torch.nn.functional as F

from . import murigate, playcheck, qmode
from .sequence import BAR, FUT_TICKS, TGT, build_window_tokens, pack_notes
from .tokens import TPB, canonicalize, decode_events
from . import v3 as V3


FANCY_SHAPES = {"VEE", "GRANDV", "P", "Q", "PP", "QQ", "S", "Z", "FAN"}


# ---------------------------------------------------------------------------------------------- window statistics
def _group_notes(notes):
    out = {}
    for n in notes:
        out.setdefault(int(n.beat), []).append(n)
    return out


def _shapes_of(notes):
    return {seg.shape for n in notes if n.kind == "slide" for arm in n.arms for seg in arm.segs}


def window_stats(notes, start, end, tempo=None):
    """Distribution features of one 4-bar window (all rates normalised by notes)."""
    ns = [n for n in notes if start <= int(n.beat) < end]
    n = len(ns)
    st = dict(n=n, npb=n / 4.0, each_rate=0.0, jack_rate=0.0, far_fast_rate=0.0, short_hold_ratio=0.0,
              slide_ratio=0.0, slide_n=0, n_shapes=0, fancy_n=0, seg4_plus=0, stream=0.0, wide=0.0)
    if n == 0:
        return st
    groups = _group_notes(ns)
    chart = [b for b, g in groups.items() for _ in range(sum(1 for x in g if x.kind not in ("touch", "thold")))]
    st["each_rate"] = sum(1 for g in groups.values() if sum(1 for x in g if x.kind not in ("touch", "thold")) >= 2) / max(n, 1)
    seq = sorted(ns, key=lambda x: (int(x.beat), x.pos, 0 if x.kind in ("tap", "hold", "slide") else 1))
    jacks = ff = wide = 0
    for a, b in zip(seq, seq[1:]):
        dt = int(b.beat) - int(a.beat)
        if dt <= 24 and a.kind not in ("touch", "thold") and b.kind not in ("touch", "thold"):
            if a.pos == b.pos:
                jacks += 1
            if abs(int(a.pos) - int(b.pos)) >= 3:
                ff += 1
        if dt <= 48 and abs(int(a.pos) - int(b.pos)) >= 3:
            wide += 1
    st["jack_rate"] = jacks / max(n, 1)
    st["far_fast_rate"] = ff / max(n, 1)
    st["wide"] = wide / max(n, 1)
    holds = [x for x in ns if x.kind in ("hold", "thold")]
    st["short_hold_ratio"] = (sum(1 for h in holds if float(getattr(h, "dur", 0.0)) * TPB <= 12) / len(holds)) if holds else 0.0
    slides = [x for x in ns if x.kind == "slide"]
    st["slide_n"] = len(slides)
    st["slide_ratio"] = len(slides) / max(n, 1)
    shapes = []
    for s in slides:
        for a in s.arms:
            for seg in a.segs:
                shapes.append(seg.shape)
    st["shapes"] = shapes
    st["n_shapes"] = len(set(shapes))
    st["fancy_n"] = sum(1 for s in shapes if s in FANCY_SHAPES)
    st["seg4_plus"] = sum(1 for s in slides for arm in s.arms if len(arm.segs) >= 4)
    onsets = sorted(groups)
    st["stream"] = sum(1 for t in onsets if t % 12 == 0) / max(len(onsets), 1)
    return st


# ---------------------------------------------------------------------------------------------- 5-part costs
def anomaly_cost(st, is_chorus):
    """(3) relative-to-official distribution anomaly.  Official Master norms: each .14-.30, jack <= .08,
    far-fast <= .05, short holds <= .15, slide share .02-.30, >= 3 slides never all one shape."""
    c = 0.0
    if st["n"] >= 8:
        if st["each_rate"] > 0.30:
            c += 2.5 * (st["each_rate"] - 0.30)
        elif st["each_rate"] < 0.14:
            c += 2.0 * (0.14 - st["each_rate"])
    c += max(0.0, st["jack_rate"] - 0.08) * 8.0
    c += max(0.0, st["far_fast_rate"] - 0.05) * 8.0
    c += max(0.0, st["short_hold_ratio"] - 0.15) * 3.0
    if st["n"] >= 8 and not (0.02 <= st["slide_ratio"] <= 0.30):
        c += 0.8 * min(abs(st["slide_ratio"] - 0.02), abs(st["slide_ratio"] - 0.30))
    if st["slide_n"] >= 3 and st["n_shapes"] <= 1:
        c += 2.0
    return c


def _seam_pair(pa, pb, boundary=False):
    """cost between the last notes of the left bar and the first notes of the right bar"""
    if not pa or not pb:
        return 0.0
    c = 0.0
    la = pa[-8:]
    fb = pb[:8]
    na, nb = len(pa) / 1.0, len(pb) / 1.0       # notes per bar
    if not boundary and abs(na - nb) > 4.0:
        c += 2.0 * (abs(na - nb) - 4.0)
    for a in la:
        for b in fb:
            dt = abs(int(b.beat) - int(a.beat))
            if dt <= 24 and a.kind not in ("touch", "thold") and b.kind not in ("touch", "thold"):
                d = abs(int(a.pos) - int(b.pos))
                if d >= 5:
                    c += 1.0
                if d == 0 and int(a.beat) != int(b.beat):
                    c += 0.5
    return c


def seam_cost(records, i, cand_notes):
    """(4) left seam (window i-1 -> i) + right seam (i -> i+1), both 1 bar wide."""
    st = records[i]["start"]
    left = records[i - 1]["notes"] if i > 0 else []
    right = records[i + 1]["notes"] if i + 1 < len(records) else []
    cur = list(cand_notes)
    c = 0.0
    c += _seam_pair([n for n in left if int(n.beat) >= st - BAR], [n for n in cur if int(n.beat) < st + BAR])
    c += _seam_pair([n for n in cur if int(n.beat) >= st + 3 * BAR], [n for n in right if int(n.beat) < st + 5 * BAR])
    return c


def cv_role_cost(st, is_chorus):
    """(5) verse calmness / chorus contrast.  Chorus windows keep D2; verse windows must stay below the official
    verse norms (npb 4.6, stream .55, wide .38, each .24)."""
    if is_chorus:
        return 0.0
    return (max(0.0, st["npb"] - 4.6) * 0.8 + max(0.0, st["stream"] - 0.55) * 1.2
            + max(0.0, st["wide"] - 0.38) * 1.5 + max(0.0, st["each_rate"] - 0.24) * 3.0)


# ---------------------------------------------------------------------------------------------- infill model helpers
def _infill_v3ctx(q):
    """Lazy per-song SongContext for the infill model (computes song encoder summary + REF embeddings once per song)."""
    gi = q.infill
    if gi is None or q.v3ctx is None:
        return None
    ctx = getattr(q, "_infill_v3ctx", None)
    if ctx is None:
        from .v3_infer import SongContext
        ctx = SongContext(gi.model, gi.V, q.v3ctx.tab, q.tempo, q.v3ctx.stats,
                          device=gi.device, plan_mode=q.v3ctx.plan_mode)
        q._infill_v3ctx = ctx
    return ctx


def _infill_view(q):
    """A lightweight q view whose model / vocab / backend point at the infill model."""
    gi = q.infill
    if gi is None:
        return None
    G = qmode._gen()
    return SimpleNamespace(options=q.options, V=gi.V, model=gi.model, backend=G.LegacyBackend(gi.model, gi.autocast),
                           tempo=q.tempo, song_beats=q.song_beats, v3ctx=_infill_v3ctx(q), rows=q.rows, log=q.log)


def build_infill_prefixes(q, records, i, notes_before, future_notes=None, with_fut=True):
    """Build prefixes for window i with history+REF from ``notes_before`` (windows 0..i-1),
    FUT block from ``future_notes`` (first 2 bars of window i+1), and full song memory for ``q.infill.model``."""
    G = qmode._gen()
    Vi = q.infill.V
    o = q.options
    start = records[i]["start"]
    if future_notes is None and with_fut and i + 1 < len(records):
        future_notes = [n for n in records[i + 1]["notes"] if start + TGT <= int(n.beat) < start + TGT + FUT_TICKS]
    packed_ctx = pack_notes(Vi, notes_before)
    packed_fut = pack_notes(Vi, future_notes or [])
    from .sequence import bpm_progress_tokens
    bt, pt = bpm_progress_tokens(Vi, q.tempo, start, q.song_beats)
    rows = records[i].get("rows", q.rows)
    ref = (Vi["REF_NONE"], [], []) if Vi.seq_version >= 3 else None
    song = None
    iv3 = _infill_v3ctx(q)
    if iv3 is not None and Vi.seq_version >= 3:
        w3 = iv3.window(start // V3.BAR, *packed_ctx, batch=len(rows), plan_shift=o.plan_shift,
                        use_plan=o.v3_plan, use_ref=o.v3_ref, use_song=o.v3_song)
        ref = w3["ref"]
        song = w3["song"]
        if not records[i].get("rows"):
            rows = G.rows_with_window(Vi, o, q.rows, w3["plan_token"], w3.get("sec_token"), w3.get("secn_token"))
    prev_tokens = len(records[i - 1]["tokens"]) if i > 0 else 384
    resv = min(o.max_target_tokens, max(256, prev_tokens + 96), q.infill.model.cfg.max_len - Vi.header_len - 2)
    prefixes = []
    for row in rows:
        row_arr = np.asarray(row, np.int32)
        p = build_window_tokens(Vi, *packed_ctx, start, row_arr, bt, pt, max_len=q.infill.model.cfg.max_len,
                                include_target=False, reserve_target_tokens=resv, ref=ref,
                                with_fut=bool(with_fut), fut=packed_fut if with_fut else None, fut_start=start + TGT)
        prefixes.append(p)
    return prefixes, song


def _tf_mean_lp(q, notes_all, records, i, cand_tokens, with_fut=True):
    """Teacher-forced mean log-prob per target token of window i under the infill model (prefix + tokens + song memory)."""
    start = records[i]["start"]
    notes_before = [n for n in notes_all if int(n.beat) < start]
    future_notes = [n for n in notes_all if start + TGT <= int(n.beat) < start + TGT + FUT_TICKS]
    prefixes, song = build_infill_prefixes(q, records, i, notes_before, future_notes=future_notes, with_fut=with_fut)
    if not prefixes or prefixes[0] is None:
        return float("-inf")
    qi = _infill_view(q)
    enc = q.infill_encode(start)
    lps = qmode.tf_logprobs(qi, enc, song, [(prefixes, list(map(int, cand_tokens)))], chunk_rows=len(prefixes))
    return float(lps[0]) / max(len(cand_tokens), 1)


def _tf_sum_lp(q, notes_all, records, i, cand, aff):
    """Summed teacher-forced log-prob of the affected windows (i+1, REF-overlapping) under the infill model (standard forward layout)."""
    out = []
    for j in aff:
        start = records[j]["start"]
        notes_before = [n for n in notes_all if int(n.beat) < start]
        prefixes, song = build_infill_prefixes(q, records, j, notes_before, future_notes=None, with_fut=False)
        if not prefixes or prefixes[0] is None:
            continue
        qi = _infill_view(q)
        enc = q.infill_encode(start)
        lp = qmode.tf_logprobs(qi, enc, song, [(prefixes, list(map(int, records[j]["tokens"])))], chunk_rows=len(prefixes))[0]
        out.append(float(lp))
    return out


# ---------------------------------------------------------------------------------------------- badness
def surprise_scores(q, records):
    """(1) bidirectional surprise: teacher-forced mean log-prob of every current window under the infill model."""
    notes = qmode.chart_notes(records)
    vals = []
    for i, r in enumerate(records):
        try:
            vals.append(_tf_mean_lp(q, notes, records, i, r["tokens"]))
        except Exception:
            vals.append(float("-inf"))
    v = np.asarray(vals, float)
    good = np.isfinite(v)
    if not good.any():
        return np.zeros(len(records)), np.zeros(len(records))
    med = float(np.median(v[good]))
    std = float(np.std(v[good])) or 1.0
    z = np.where(good, (med - v) / std, 0.0)
    return z, v


def infill_window_badness(q, records, w_surprise=1.0):
    """5-part per-window cost.  Components: surprise, qmode (rules+muri+hand+stuck+guard), anomaly, seam, cv_role."""
    base, ev = qmode.window_badness(q, records)
    z, lp = surprise_scores(q, records)
    n = len(records)
    out = []
    for i, c in enumerate(base):
        st = window_stats(records[i]["notes"], records[i]["start"], records[i]["end"], q.tempo)
        is_chorus = bool(records[i]["stats"].get("chorus", False))
        comp = dict(c)
        comp["surprise"] = float(w_surprise * max(0.0, z[i]))
        comp["anomaly"] = float(anomaly_cost(st, is_chorus))
        comp["seam"] = float(seam_cost(records, i, records[i]["notes"]))
        comp["cv_role"] = float(cv_role_cost(st, is_chorus))
        comp["lp"] = float(lp[i])
        comp["total"] = float(c["total"] + comp["surprise"] + comp["anomaly"] + comp["seam"] + comp["cv_role"])
        out.append(comp)
    return out, ev


# ---------------------------------------------------------------------------------------------- one window
def _region_playcheck(q, records, i, cand_notes):
    """Detail 4.3: combined [window i-1 tail, candidate i, window i+1] playcheck + full muri cost (hard + soft)."""
    st = records[i]["start"]
    lo = records[i - 1]["start"] if i > 0 else st
    hi = records[i + 1]["end"] if i + 1 < len(records) else records[i]["end"]
    notes = []
    if i > 0:
        notes += [n for n in records[i - 1]["notes"] if int(n.beat) >= st - BAR]
    notes += list(cand_notes)
    if i + 1 < len(records):
        notes += [n for n in records[i + 1]["notes"] if int(n.beat) < st + 5 * BAR]
    pc = playcheck.check(canonicalize(notes), q.tempo, stats=False)
    gate = q.refine_gate
    muri_cost = 0.0
    hard = 0
    if gate is not None:
        sub = [n for n in notes if gate._sec(n.end_beat()) >= gate._sec(lo) - gate.pre and gate._sec(n.beat) <= gate._sec(hi) + gate.post]
        evs = gate._events(sub, gate._sec(lo), gate._sec(hi) + gate.margin) if sub else []
        if evs:
            cnt = Counter(murigate.CAT_KEY[e["category"]] for e in evs)
            muri_cost, hard = qmode.muri_full(gate, cnt)
        extra = murigate.static_overlaps(sub, lo, hi) if sub else 0
        if extra:
            hard += int(extra)
            muri_cost += gate.w_hard * 2 * int(extra)
    return pc["n_viol"], int(hard), float(muri_cost)


def _window_audio_onset_f1(q, st, notes, start, end, tol=1):
    """Audio-onset F1 of one window's note onsets against the song's flux peaks.

    The comparison is deliberately local and fixed-reference: both the existing and the candidate
    window are scored against the same per-tick audio onset envelope, so a replacement can never
    buy a lower regional cost by moving notes away from audible onsets.  ``ChorusState.onset`` is
    already available in the normal D2/rwo path; the cached fallback makes the gate work for every
    generation protocol.
    """
    from . import chorus as chorus_mod
    strength = None
    chorus_state = getattr(st.scorer, "chorus", None)
    if chorus_state is not None:
        strength = getattr(chorus_state, "onset", None)
    if strength is None:
        strength = getattr(q, "_infill_onset_strength", None)
        if strength is None and getattr(q, "mel", None) is not None:
            try:
                strength = chorus_mod.onset_strength(
                    q.mel, q.tempo, q.first, q.end_tick,
                    float(getattr(q.options, "chorus_onset_tol", 1.0) or 1.0))
                q._infill_onset_strength = strength
            except Exception:
                strength = None
    if strength is None or len(strength) == 0:
        return None
    s = np.asarray(strength, np.float64)
    lo, hi = max(0, int(start)), min(len(s), int(end))
    if hi <= lo:
        return 0.0
    thr = float(np.quantile(s, 0.85))
    allowed = s[lo:hi] >= max(thr, 1e-9)
    # Merge contiguous allowed ticks into one audible onset event.  A single spectral onset spans
    # more than one grid tick at slow tempos; counting the raw mask would reward duplicate notes.
    events = []
    j = 0
    while j < len(allowed):
        if not allowed[j]:
            j += 1
            continue
        k = j + 1
        while k < len(allowed) and allowed[k]:
            k += 1
        events.append(lo + (j + k - 1) // 2)
        j = k
    chart = sorted({int(round(float(n.beat))) for n in notes
                    if lo <= int(round(float(n.beat))) < hi and n.kind != "thold"})
    if not events and not chart:
        return 1.0
    if not events or not chart:
        return 0.0

    def matched(a, b):
        i = j = hit = 0
        while i < len(a) and j < len(b):
            d = int(a[i]) - int(b[j])
            if abs(d) <= tol:
                hit += 1
                i += 1
                j += 1
            elif d < 0:
                i += 1
            else:
                j += 1
        return hit

    hit = matched(chart, events)
    precision = hit / max(1, len(chart))
    recall = hit / max(1, len(events))
    return 2.0 * precision * recall / max(precision + recall, 1e-9)


class _PadBias:
    """Wrap a Steer built for the 2235-token vocabulary and pad its logit bias to the infill vocab (FUT row 0)."""

    def __init__(self, bias, n):
        self.bias, self.n = bias, int(n)

    def __call__(self, grammar, guard):
        sb = self.bias(grammar, guard)
        if sb is None:
            return None
        dense = getattr(sb, "dense", None)
        if dense is not None and np.asarray(dense).shape[-1] < self.n:
            d = np.asarray(dense)
            pad = np.zeros(d.shape[:-1] + (self.n - d.shape[-1],), d.dtype)
            sb.dense = np.concatenate([d, pad], axis=-1)
        return sb


def infill_refine_window(q, records, i, p, log):
    """Regenerate window i with K FUT-conditioned candidates; return (accepted, info). Generator."""
    G = qmode._gen()
    o = q.options
    Vi = q.infill.V
    t0 = time.perf_counter()
    rec = records[i]
    start, end = rec["start"], rec["end"]
    prior = records[i - 1]["notes"] if i > 0 else []
    # FUT source: 2 bars of the next window from the CURRENT draft
    future = [n for n in records[i + 1]["notes"] if start + TGT <= int(n.beat) < start + TGT + FUT_TICKS] if i + 1 < len(records) else []
    if not future:
        return False, dict(window=i, pass_=p, skipped="no-future")
    st = qmode.replay(q, records, i, with_tracker=True)
    notes_ctx = list(st.notes)
    # prefix with history + REF from notes_ctx AND FUT from future, plus song encoder memory
    prefixes, song = build_infill_prefixes(q, records, i, notes_ctx, future_notes=future, with_fut=True)
    if prefixes[0] is None:
        return False, dict(window=i, pass_=p, skipped="prefix")
    holds = [n for n in st.notes if n.kind in ("hold", "thold") and n.beat + n.dur > start]
    base = G.HandGuard(Vi, q.tempo, start, q.end_tick, st.tracker, o.prune_end)
    base.holds = holds
    base.recent = [n for n in st.notes if n.beat >= start - 6 * BAR]
    st.scorer.scale = rec["scale"]
    st.bias.begin_window(i, start, st.notes)
    enc = q.infill_encode(start)
    K = max(1, int(o.infill_k))
    backend = G.LegacyBackend(q.infill.model, q.infill.autocast)
    pool, seen = [], set()
    for rnd in range(2):
        guards = [base.clone() for _ in range(K)]

        seed_offset = int(getattr(o, "infill_seed_offset", 0) or 0)
        round_offset = int(getattr(o, "infill_round", 0) or 0)

        def rng_factory(k, attempt, _rnd=rnd):
            # A fresh seed bank per evolution round is essential: otherwise R2/R3 would
            # replay the exact R1 candidate pool when they refine the same source charts.
            return np.random.default_rng([
                int(q.seed) + 1000003 * seed_offset + 7919 * round_offset,
                9000 + 100 * p + _rnd, int(i), int(k), int(attempt)])

        results = yield from G.decode_candidates_co(q.infill.model, enc, prefixes, o, Vi, guards, rng_factory,
                                                    int(TGT), bias=_PadBias(st.bias, Vi.size), backend=backend, song=song)
        for k, (tokens, probs, stats) in enumerate(results):
            nn = canonicalize(decode_events(Vi, tokens, start))
            key = tuple(qmode.simai_key(n) for n in nn)
            if key in seen:
                continue
            seen.add(key)
            pool.append(dict(notes=nn, tokens=tokens, probs=probs, stats=stats, guard=guards[k],
                             mean_lp=float(np.mean(probs)) if probs else -10.0))
        if pool or rnd == 1:
            break
    st.bias.tilt_shift = 0.0
    ex_key = tuple(qmode.simai_key(n) for n in rec["notes"])
    pool = [c for c in pool if tuple(qmode.simai_key(n) for n in c["notes"]) != ex_key and not c["stats"]["fallback"]]
    info = dict(window=i, pass_=p, candidates=len(pool), k=K)
    if not pool:
        info.update(accepted=False, reason="no candidate")
        return False, info
    # cheap costs
    for c in pool:
        c["rules"], c["hand"], c["parts"] = qmode.region_cost(q, records, st, i, c)
        cst = window_stats(c["notes"], start, end, q.tempo)
        c["cst"] = cst
        c["anomaly"] = anomaly_cost(cst, bool(rec["stats"].get("chorus", False)))
        c["seam"] = seam_cost(records, i, c["notes"])
        c["cv_role"] = cv_role_cost(cst, bool(rec["stats"].get("chorus", False)))
        c["base"] = c["rules"] + c["hand"] + c["anomaly"] + c["seam"] + c["cv_role"]
    ex_st = window_stats(rec["notes"], start, end, q.tempo)
    is_chorus = bool(rec["stats"].get("chorus", False))
    ex_rules, ex_hand, ex_parts = qmode.region_cost(q, records, st, i, dict(notes=rec["notes"], tokens=rec["tokens"],
                                                                             mean_lp=rec["mean_lp"]))
    ex = dict(notes=rec["notes"], tokens=rec["tokens"], mean_lp=rec["mean_lp"], rules=ex_rules, hand=ex_hand,
              parts=ex_parts,
              cst=ex_st,
              anomaly=anomaly_cost(ex_st, is_chorus), seam=seam_cost(records, i, rec["notes"]),
              cv_role=cv_role_cost(ex_st, is_chorus))
    ex["base"] = ex["rules"] + ex["hand"] + ex["anomaly"] + ex["seam"] + ex["cv_role"]
    ex["onset_f1"] = _window_audio_onset_f1(q, st, ex["notes"], start, end)
    ex["pick"] = float(ex_parts.get("p_chorus", 0.0)) if ex_parts else 0.0
    pool.sort(key=lambda c: c["base"])
    evals = [ex] + pool[:max(1, min(o.refine_eval, len(pool)))]
    # (1) surprise / teacher-forced lp of the affected windows
    aff = qmode.affected_windows(q, records, i)
    notes_full = qmode.chart_notes(records)
    med_lp = float(np.median([r["mean_lp"] for r in records])) if records else 0.0
    for c in evals:
        nviol, hard, muri_cost = _region_playcheck(q, records, i, c["notes"])
        c["nviol"], c["hard"], c["muri"] = nviol, hard, muri_cost
        c["onset_f1"] = _window_audio_onset_f1(q, st, c["notes"], start, end)
        c["pick"] = float(c["parts"].get("p_chorus", 0.0)) if c.get("parts") else 0.0
        notes_mod = list(notes_ctx) + list(c["notes"]) + [n for j in range(i + 1, len(records)) for n in records[j]["notes"]]
        try:
            c["lp_i"] = _tf_mean_lp(q, notes_mod, records, i, c["tokens"])
        except Exception:
            c["lp_i"] = float("-inf")
        try:
            c["lp_aff"] = sum(_tf_sum_lp(q, notes_mod, records, i, c, aff)) if aff else 0.0
        except Exception:
            c["lp_aff"] = 0.0
    ex["lp_i"], ex["lp_aff"] = evals[0].get("lp_i", 0.0), evals[0].get("lp_aff", 0.0)

    def total(c):
        sur = max(0.0, (med_lp - c.get("lp_i", med_lp))) if math.isfinite(c.get("lp_i", med_lp)) else 0.0
        return c["base"] + c.get("muri", 0.0) + 1.0 * sur - o.refine_lp * c.get("lp_aff", 0.0)

    for c in evals:
        c["total"] = total(c)
    info.update(existing=dict(total=round(ex["total"], 3), base=round(ex["base"], 3), lp=round(ex.get("lp_i", 0), 3)))
    # Rank by total cost first.  A fancy-looking but expensive candidate must not hide
    # a cheaper valid candidate behind the margin early-exit below; fancy_n is already
    # a hard non-regression gate.
    ranked = sorted(pool[:len(evals) - 1], key=lambda c: c["total"])
    info["best"] = [dict(total=round(c["total"], 3)) for c in ranked[:3]]
    info["top"] = [dict(total=round(c["total"], 3),
                        onset_f1=None if c.get("onset_f1") is None else round(float(c["onset_f1"]), 4),
                        pick=round(float(c.get("pick", 0.0)), 4),
                        nviol=int(c.get("nviol", 0)), hard=int(c.get("hard", 0)),
                        muri=round(float(c.get("muri", 0.0)), 3),
                        each_rate=round(float(c["cst"]["each_rate"]), 4),
                        npb=round(float(c["cst"]["npb"]), 3),
                        wide=round(float(c["cst"]["wide"]), 4),
                        slide_n=int(c["cst"]["slide_n"]), n_shapes=int(c["cst"]["n_shapes"]),
                        fancy_n=int(c["cst"].get("fancy_n", 0)), seg4_plus=int(c["cst"].get("seg4_plus", 0)),
                        notes=len(c["notes"])) for c in ranked]
    info["existing"].update(
        onset_f1=None if ex.get("onset_f1") is None else round(float(ex["onset_f1"]), 4),
        pick=round(float(ex.get("pick", 0.0)), 4),
        nviol=int(ex.get("nviol", 0)), hard=int(ex.get("hard", 0)),
        muri=round(float(ex.get("muri", 0.0)), 3),
        each_rate=round(float(ex_st["each_rate"]), 4),
        npb=round(float(ex_st["npb"]), 3), wide=round(float(ex_st["wide"]), 4),
        slide_n=int(ex_st["slide_n"]), n_shapes=int(ex_st["n_shapes"]),
        fancy_n=int(ex_st.get("fancy_n", 0)), seg4_plus=int(ex_st.get("seg4_plus", 0)), notes=len(ex["notes"]))
    rejected = Counter()
    for c in ranked:
        if c["total"] > ex["total"] - o.infill_margin:
            rejected["margin"] += 1
            break
        # Hard musical-fidelity gate: never trade an audible onset for a cheaper regional score,
        # and never worsen the chorus pick penalty (lower is better).
        if ex["onset_f1"] is not None and c["onset_f1"] is not None and c["onset_f1"] + 1e-12 < ex["onset_f1"]:
            rejected["onset_f1"] += 1
            continue
        if c["pick"] > ex["pick"] + 1e-12:
            rejected["chorus_pick"] += 1
            continue
        if c["nviol"] > 0 or c["hard"] > ex["hard"] or c["muri"] > ex["muri"] + 1e-6:
            rejected["playcheck_or_muri"] += 1
            continue
        cst = c["cst"]
        # Strict flavor & structural preservation: never drop slides, never drain or bloat chords, preserve Chorus vs Verse role
        if cst["slide_n"] < ex_st["slide_n"] or cst["n_shapes"] < ex_st["n_shapes"]:
            rejected["slides_or_shapes"] += 1
            continue
        if cst["seg4_plus"] > 0:
            rejected["seg4_plus"] += 1
            continue
        if cst["fancy_n"] < ex_st["fancy_n"]:
            rejected["fancy"] += 1
            continue
        if abs(cst["each_rate"] - ex_st["each_rate"]) > 0.030:
            rejected["each_delta"] += 1
            continue
        # 360-degree window-level Pareto dominance: a replacement may never buy a lower
        # regional score by spending hand pressure, rule errors, or the chorus/verse role.
        if c["hand"] > ex["hand"] + 1e-6:
            rejected["hand"] += 1
            continue
        if c["rules"] > ex["rules"] + 1e-6:
            rejected["rules"] += 1
            continue
        if cst["jack_rate"] > ex_st["jack_rate"] + 1e-6:
            rejected["jack_rate"] += 1
            continue
        if cst["far_fast_rate"] > ex_st["far_fast_rate"] + 1e-6:
            rejected["far_fast_rate"] += 1
            continue
        if is_chorus:
            if (cst["npb"] < ex_st["npb"] - 0.25
                    or cst["wide"] < ex_st["wide"]
                    or cst["stream"] < ex_st["stream"] - 0.005
                    or cst["each_rate"] < min(ex_st["each_rate"], 0.24)):
                rejected["chorus_role"] += 1
                continue
        else:
            if (cst["npb"] > ex_st["npb"] + 0.25
                    or cst["wide"] > ex_st["wide"]
                    or cst["stream"] > ex_st["stream"] + 0.01
                    or cst["each_rate"] > ex_st["each_rate"]):
                rejected["verse_role"] += 1
                continue
        # Whole-chart shape diversity is a global (not just local) invariant: replacing
        # a window must never delete the last occurrence of a slide shape from the chart.
        outside = set()
        for j, rr in enumerate(records):
            if j != i:
                outside.update(_shapes_of(rr["notes"]))
        old_global = outside | _shapes_of(rec["notes"])
        new_global = outside | set(cst.get("shapes", []))
        if len(new_global) < len(old_global):
            rejected["global_n_shapes"] += 1
            continue
        # accept
        new_stats = dict(rec["stats"])
        new_stats.update(c["stats"])
        new_stats.update(notes=len(c["notes"]), chosen=-1, refined_infill=p + 1,
                         infill_cost=round(c["total"], 3), infill_base=round(c["base"], 3))
        rec_new = dict(rec)
        rec_new.update(notes=c["notes"], tokens=c["tokens"], probs=c["probs"], mean_lp=c["mean_lp"], stats=new_stats)
        records[i] = rec_new
        info.update(accepted=True, delta=round(ex["total"] - c["total"], 3),
                    onset_f1=round(float(c["onset_f1"]), 4) if c["onset_f1"] is not None else None,
                    onset_f1_ex=round(float(ex["onset_f1"]), 4) if ex["onset_f1"] is not None else None,
                    pick=round(float(c["pick"]), 4), pick_ex=round(float(ex["pick"]), 4),
                    seconds=round(time.perf_counter() - t0, 2))
        info["rejected"] = dict(rejected)
        return True, info
    info.update(accepted=False, reason="no improvement", rejected=dict(rejected),
                seconds=round(time.perf_counter() - t0, 2))
    return False, info


